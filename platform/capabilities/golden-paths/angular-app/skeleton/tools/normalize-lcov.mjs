import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

/** Angular/Vitest emits dist/test-out/<run>/src/... paths in LCOV.
 *  Rebase records to existing repository sources, without inventing coverage.
 */
export function sourceFile(path, root = process.cwd()) {
  const clean = path.replaceAll('\\', '/');
  const match = clean.match(/(?:^|\/)src\/(.+)$/);
  if (!match) throw new Error(`Cannot resolve LCOV source: ${path}`);
  const normalized = `src/${match[1]}`;
  if (!existsSync(join(root, normalized))) {
    throw new Error(`LCOV source does not exist: ${normalized} (from ${path})`);
  }
  return normalized;
}

export function normalizeLcov(raw, root = process.cwd()) {
  let records = 0;
  const normalized = raw.split(/\r?\n/).map(line => {
    if (!line.startsWith('SF:')) return line;
    records += 1;
    return 'SF:' + sourceFile(line.slice(3), root);
  }).join('\n');
  if (records === 0) throw new Error('LCOV input contains no SF source records');
  return normalized;
}

function candidates(folder) {
  if (!existsSync(folder)) return [];
  return readdirSync(folder, { withFileTypes: true }).flatMap(item => {
    const child = join(folder, item.name);
    if (item.isDirectory()) return candidates(child);
    return item.name === 'lcov.info' ? [child] : [];
  });
}

export function normalizeCoverage(root = process.cwd()) {
  const list = [...new Set([...candidates(join(root, 'coverage')), ...candidates(join(root, 'dist', 'test-out'))])];
  if (!list.length) throw new Error('No lcov.info generated by ng test');
  const input = list.sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs)[0];
  const output = join(root, 'coverage', 'lcov.info');
  const result = normalizeLcov(readFileSync(input, 'utf8'), root);
  mkdirSync(join(root, 'coverage'), { recursive: true });
  writeFileSync(output, result);
  console.log(`Normalized LCOV from ${relative(root, input)} to coverage/lcov.info`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  normalizeCoverage();
}
